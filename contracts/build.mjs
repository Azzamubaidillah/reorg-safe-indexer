// Regenerates apps/indexer/test/anvil/support/bytecode.generated.ts from contracts/src.
// Run `node contracts/build.mjs` after editing a contract and commit the result. CI never compiles:
// forge would download solc, and the committed bytecode keeps the test chain byte-for-byte reproducible.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL(".", import.meta.url));
const target = fileURLToPath(new URL("../apps/indexer/test/anvil/support/bytecode.generated.ts", import.meta.url));

execFileSync("forge", ["build", "--root", root], { stdio: "inherit" });

const names = ["TransferEmitter", "SwapEmitter"];
const lines = ["// Generated by contracts/build.mjs from contracts/src/Emitters.sol. Do not edit.", ""];
for (const name of names) {
  const artifact = JSON.parse(readFileSync(`${root}out/Emitters.sol/${name}.json`, "utf8"));
  const bytecode = artifact.bytecode.object;
  if (!/^0x[0-9a-f]+$/.test(bytecode)) throw new Error(`${name}: unexpected bytecode`);
  lines.push(`export const ${name[0].toLowerCase()}${name.slice(1)}Bytecode = "${bytecode}" as const;`);
}
writeFileSync(target, `${lines.join("\n")}\n`);
